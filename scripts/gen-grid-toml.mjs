#!/usr/bin/env node
// Generates the Dynamic Grid TOML files from browser-images/catalog.json.
// `node scripts/gen-grid-toml.mjs --check` fails if the committed files are stale (used by tests/CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const GRID_BROWSER_NAMES = { chrome: 'chrome', edge: 'MicrosoftEdge', firefox: 'firefox' };
// Never add "Binds" (it would copy the Grid's docker.sock mount into every browser container) or devices/privileged keys.
export const HOST_CONFIG_KEYS = ['Dns', 'DnsOptions', 'DnsSearch', 'ExtraHosts'];
// Reaps sessions whose WebDriver went quiet; the API sends a keepalive every 60 s while a session is open.
export const SESSION_TIMEOUT_SECONDS = 300;

// Grid 4.51 needs a tagged image (it names containers from RepoTags), so the TOML uses tags and
// docker/grid-entrypoint.sh enforces each `# pin` line: the tag is (re)pointed at the pinned digest before Grid starts.
export const pinLine = (e) => (e.imageDigest ? `# pin ${e.image} ${e.imageDigest}` : `# local ${e.image} ${e.buildRecipe}`);

export function stereotype(e) {
  return {
    browserName: GRID_BROWSER_NAMES[e.family],
    browserVersion: e.requestedVersion,
    platformName: e.platformName,
    'browserlab:catalogId': e.id,
  };
}

/** profile: 'default' or 'legacy' (legacy also includes default entries). */
export function renderToml(catalog, arch, profile) {
  const profiles = profile === 'legacy' ? ['default', 'legacy'] : ['default'];
  const entries = catalog.entries.filter(
    (e) => e.provider === 'selenium-docker' && profiles.includes(e.gridProfile) && e.architectures.includes(arch),
  );
  if (!entries.length) return null;
  const configs = entries.map((e) => `  "${e.image}", '${JSON.stringify(stereotype(e))}'`).join(',\n');
  return `# GENERATED by scripts/gen-grid-toml.mjs from browser-images/catalog.json. Do not edit by hand.
# Grid ${catalog.gridRelease} Dynamic Grid, ${arch}, profile "${profile}".
${entries.map(pinLine).join('\n')}
[docker]
configs = [
${configs}
]
host-config-keys = ${JSON.stringify(HOST_CONFIG_KEYS)}
# In-container socat (bound to 127.0.0.1 inside the grid container) in front of the mounted docker.sock.
url = "http://127.0.0.1:2375"
video-image = "false"

[node]
session-timeout = ${SESSION_TIMEOUT_SECONDS}
enable-managed-downloads = true

[distributor]
# Fail fast instead of queueing a request no slot can ever serve.
reject-unsupported-caps = true
`;
}

export function targets(catalog) {
  const out = {};
  for (const arch of ['amd64', 'arm64'])
    for (const profile of ['default', 'legacy']) {
      const toml = renderToml(catalog, arch, profile);
      if (toml) out[`browser-images/grid-${profile}-${arch}.toml`] = toml;
    }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = JSON.parse(readFileSync(`${root}/browser-images/catalog.json`, 'utf8'));
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, toml] of Object.entries(targets(catalog))) {
    let current = '';
    try { current = readFileSync(`${root}/${file}`, 'utf8'); } catch { /* missing */ }
    if (current === toml) continue;
    if (check) { console.error(`stale: ${file}`); stale = true; } else { writeFileSync(`${root}/${file}`, toml); console.log(`wrote ${file}`); }
  }
  if (stale) { console.error('Run: npm run catalog:toml'); process.exit(1); }
}
